#!/usr/bin/env python3
"""Regenerate docs/graph.md and web/data.js from data/prophecies.yaml.

Usage:  python scripts/build.py
Requires: pyyaml
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "prophecies.yaml"
GRAPH_MD = ROOT / "docs" / "graph.md"
WEB_DATA = ROOT / "web" / "data.js"

THEME_ORDER = [
    "lineage", "covenant", "birth", "forerunner", "ministry",
    "suffering", "death", "resurrection", "exaltation", "kingdom", "return",
]
KIND_LABEL = {
    "tanakh": "Tanakh", "targum": "Targum", "talmud": "Talmud",
    "midrash": "Midrash", "qumran": "Qumran",
}


def load() -> list[dict]:
    with DATA.open(encoding="utf-8") as fh:
        entries = yaml.safe_load(fh)
    ids = [e["id"] for e in entries]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        sys.exit(f"duplicate ids: {sorted(dup)}")
    return entries


def validate(entries: list[dict]) -> list[str]:
    """Return a list of warnings; hard errors exit."""
    warnings: list[str] = []
    ids = {e["id"] for e in entries}
    for e in entries:
        src = e.get("source") or {}
        for key in ("ref", "lang", "text", "english"):
            if key not in src:
                sys.exit(f"{e['id']}: source.{key} missing")
        if e.get("theme") not in THEME_ORDER:
            sys.exit(f"{e['id']}: unknown theme {e.get('theme')!r}")
        if "jewish_reading" not in e:
            warnings.append(f"{e['id']}: no jewish_reading")
        for rid in e.get("relates_to", []):
            if rid not in ids:
                sys.exit(f"{e['id']}: relates_to unknown id {rid}")
        words = e.get("words")
        if words:
            tokens = [t for t in src["text"].split() if t != "..."]
            ws = [w["w"] for w in words]
            if ws != tokens:
                warnings.append(
                    f"{e['id']}: words list does not match source.text tokens\n"
                    f"    text : {tokens}\n    words: {ws}"
                )
    return warnings


def mermaid_id(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def short_ref(ref: str) -> str:
    ref = re.sub(r"\s*\[[^\]]*\]", "", ref)  # drop [16] bracket numbers
    ref = ref.replace("Targum Jonathan on ", "Tg ")
    return ref


def key_word(e: dict) -> str:
    """A short original-language fragment for the node label."""
    words = e["source"]["text"].split()
    words = [w for w in words if w != "..."]
    return " ".join(words[:3]) + (" …" if len(words) > 3 else "")


def build_graph_md(entries: list[dict]) -> str:
    lines: list[str] = []
    a = lines.append
    a("# Prophecy graph")
    a("")
    a("Generated by `scripts/build.py` from `data/prophecies.yaml`. Do not edit by hand.")
    a("")
    a("Themes → source passages → New Testament fulfilment claims. Dashed edges link a "
      "Targum, Talmud or Qumran entry to the Tanakh passage it comments on. Green nodes are "
      "Jewish texts outside the Tanakh.")
    a("")
    a("```mermaid")
    a("flowchart LR")
    a("    classDef theme fill:#2b2d42,color:#fff,stroke:none")
    a("    classDef heb fill:#fff3cd,stroke:#b8860b,color:#000")
    a("    classDef arc fill:#ffe8cc,stroke:#c2410c,color:#000")
    a("    classDef grk fill:#d7e3fc,stroke:#1d4ed8,color:#000")
    a("    classDef jew fill:#e8f5e9,stroke:#2e7d32,color:#000,stroke-dasharray:4 2")
    a("")
    themes_used = [t for t in THEME_ORDER if any(e["theme"] == t for e in entries)]
    a("    subgraph Themes")
    for t in themes_used:
        a(f"        T_{t}[{t.capitalize()}]:::theme")
    a("    end")
    a("")
    tanakh = [e for e in entries if (e["source"].get("kind", "tanakh")) == "tanakh"]
    other = [e for e in entries if (e["source"].get("kind", "tanakh")) != "tanakh"]
    a('    subgraph Tanakh ["Tanakh (Hebrew / Aramaic)"]')
    for e in tanakh:
        cls = "arc" if e["source"]["lang"] == "arc" else "heb"
        a(f'        {mermaid_id(e["id"])}["{short_ref(e["source"]["ref"])}<br/>{key_word(e)}<br/>{e["title"]}"]:::{cls}')
    a("    end")
    a("")
    if other:
        a('    subgraph Jewish ["Targum · Talmud · Qumran"]')
        for e in other:
            kind = KIND_LABEL.get(e["source"].get("kind"), "")
            a(f'        {mermaid_id(e["id"])}["{short_ref(e["source"]["ref"])}<br/>{key_word(e)}<br/>{e["title"]}"]:::jew')
        a("    end")
        a("")
    a('    subgraph NT ["New Testament (Greek)"]')
    nt_nodes: dict[str, str] = {}
    for e in entries:
        for f in e.get("fulfilment", []) or []:
            nid = "nt_" + mermaid_id(f["ref"])
            if nid not in nt_nodes:
                frag = " ".join(f["text"].split()[:4])
                nt_nodes[nid] = f'        {nid}["{f["ref"]}<br/>{frag}"]:::grk'
    for line in nt_nodes.values():
        a(line)
    a("    end")
    a("")
    for t in themes_used:
        members = [mermaid_id(e["id"]) for e in entries if e["theme"] == t]
        a(f"    T_{t} --> {' & '.join(members)}")
    a("")
    for e in entries:
        for f in e.get("fulfilment", []) or []:
            a(f"    {mermaid_id(e['id'])} --> nt_{mermaid_id(f['ref'])}")
    a("")
    for e in entries:
        for rid in e.get("relates_to", []) or []:
            a(f"    {mermaid_id(e['id'])} -.-> {mermaid_id(rid)}")
    a("```")
    a("")
    a("## Reading the graph")
    a("")
    a("- **Yellow**: Hebrew source text. **Orange**: Aramaic (Daniel 7).")
    a("- **Blue**: Greek New Testament text that claims fulfilment.")
    a("- **Green, dashed border**: a Targum, Talmud or Qumran text that reads a passage messianically, "
      "linked by a dashed edge to the passage it comments on.")
    a("- Open `web/index.html` for the interactive version with side-by-side text and word glosses.")
    a("")
    return "\n".join(lines)


def build_web_data(entries: list[dict]) -> str:
    payload = json.dumps(entries, ensure_ascii=False, indent=1)
    return (
        "// Generated by scripts/build.py from data/prophecies.yaml. Do not edit.\n"
        f"window.MESHIACH = {payload};\n"
    )


def main() -> None:
    entries = load()
    for w in validate(entries):
        print("warning:", w, file=sys.stderr)
    GRAPH_MD.write_text(build_graph_md(entries), encoding="utf-8", newline="\n")
    WEB_DATA.parent.mkdir(exist_ok=True)
    WEB_DATA.write_text(build_web_data(entries), encoding="utf-8", newline="\n")
    n_words = sum(1 for e in entries if e.get("words"))
    print(f"{len(entries)} entries ({n_words} with word glosses) -> {GRAPH_MD.relative_to(ROOT)}, {WEB_DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
